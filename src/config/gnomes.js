// Гномы. Работают на острове вместо игрока за золото. Только данные.
//
// Первый гном (слот 0) делает всё сам. Остальные гномы живут в пещере гномов и имеют специальность:
// farmer — сажает, поливает и собирает урожай, porter — носит еду из загона и с грядок в амбар, fixer — чинит постройки (дерево берёт из амбара).
// Зарплата платится раз в сутки и зависит от уровня гнома. Нет золота — гном бастует, второй день подряд — уходит.
// Гномы набираются опыта от работы и работают лучше. Рейдеры могут их ранить и убить (тогда нужно обучить нового).
export const GNOME = {
  baseWage: 6,            // зарплата гнома 1 уровня за сутки
  wageStep: 3,            // прибавка за каждый следующий уровень
  trainFee: 30,           // обучение нового гнома (после гибели или для пещеры)
  tasksPerLevel: 20,      // сколько дел нужно для следующего уровня (умножается на текущий уровень)
  maxLevel: 5,
  hp: [40, 50, 60, 70, 80],
  speed: 2.4, speedStep: 0.3,      // скорость ходьбы и прибавка за уровень
  workTime: 2.2,                   // секунд на одно дело (на 1 уровне)
  levelSpeed: 0.15,                // на сколько быстрее работа за каждый уровень
  specBonus: 1.4,                  // специалист работает быстрее в своём деле
  carry: 6, carryStep: 2,          // сколько несёт и прибавка за уровень
  fixAmount: 40,                   // сколько прочности чинит за дело (дерево 3)
  specs: ['farmer', 'porter', 'fixer'],
  caveSlots: [2, 3, 4],            // сколько мест открывает пещера уровня 1, 2, 3 (кроме первого гнома)
  questAmounts: [6, 8, 10, 12],    // поручение дня: принеси столько еды, награда — золото
  questReward: 2,                  // награда = amount / 2 + questReward
};

export const wageOf = level => GNOME.baseWage + GNOME.wageStep * (level - 1);
